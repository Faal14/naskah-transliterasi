"use client";

import { useState, useEffect } from "react";

type Annotation = {
  id: string;
  x: number;
  y: number;
  w: number;
  h: number;
  transliteration: string;
  translation: string;
  notes: string | null;
  pegonText: string | null;
  contributorName: string;
};

export default function PublicCanvas({
  imageUrl,
  annotations,
  fullTransliteration,
  fullTranslation,
  fullApparatus: _fullApparatus,
}: {
  imageUrl: string;
  annotations: Annotation[];
  fullTransliteration: string;
  fullTranslation: string;
  fullApparatus: string;
}) {
  const [hoveredAnn, setHoveredAnn] = useState<Annotation | null>(null);
  const [selectedAnn, setSelectedAnn] = useState<Annotation | null>(null);
  const [voiceSupported, setVoiceSupported] = useState(false);
  const [speakingId, setSpeakingId] = useState<string | null>(null);

  useEffect(() => {
    if (typeof window !== "undefined" && "speechSynthesis" in window) {
      // eslint-disable-next-line react-hooks/set-state-in-effect
      setVoiceSupported(true);
    }
    return () => {
      if (typeof window !== "undefined" && "speechSynthesis" in window) {
        window.speechSynthesis.cancel();
      }
    };
  }, []);

  const sortedAnnotations = [...annotations].sort((a, b) => {
    if (Math.abs(a.y - b.y) > 0.02) return a.y - b.y;
    return a.x - b.x;
  });

  const translitParagraph =
    sortedAnnotations.length > 0
      ? sortedAnnotations.map((a) => a.transliteration).join(" ")
      : fullTransliteration.trim();

  const translationParagraph =
    sortedAnnotations.length > 0
      ? sortedAnnotations.map((a) => a.translation).join(" ")
      : fullTranslation.trim();

  const isAutoGenerated = !fullTransliteration.trim() && annotations.length > 0;

  function findIndonesianVoice(): SpeechSynthesisVoice | null {
    if (!voiceSupported) return null;
    const voices = window.speechSynthesis.getVoices();
    return (
      voices.find((v) => v.lang === "id-ID") ||
      voices.find((v) => v.lang.startsWith("id")) ||
      null
    );
  }

  function speak(text: string, id: string) {
    if (!voiceSupported) return;
    if (speakingId === id) {
      window.speechSynthesis.cancel();
      setSpeakingId(null);
      return;
    }
    window.speechSynthesis.cancel();
    const utt = new SpeechSynthesisUtterance(text);
    utt.lang = "id-ID";
    utt.rate = 0.9;
    const voice = findIndonesianVoice();
    if (voice) utt.voice = voice;
    utt.onend = () => setSpeakingId(null);
    utt.onerror = () => setSpeakingId(null);
    window.speechSynthesis.speak(utt);
    setSpeakingId(id);
  }

  const activeAnn = hoveredAnn || selectedAnn;

  const tooltipPosition = (() => {
    if (!hoveredAnn) return null;
    const centerX = (hoveredAnn.x + hoveredAnn.w / 2) * 100;
    const isTooCloseToTop = hoveredAnn.y < 0.12;

    if (isTooCloseToTop) {
      return {
        left: `${centerX}%`,
        top: `${(hoveredAnn.y + hoveredAnn.h) * 100}%`,
        transform: "translate(-50%, 12px)",
        arrowAtTop: true,
      };
    }
    return {
      left: `${centerX}%`,
      top: `${hoveredAnn.y * 100}%`,
      transform: "translate(-50%, -100%) translateY(-14px)",
      arrowAtTop: false,
    };
  })();

  return (
    <div className="space-y-4">
      <div className="flex items-center gap-2 text-sm flex-wrap">
        <span className="text-slate-500 text-xs">
          {annotations.length} kata terverifikasi
        </span>
        {isAutoGenerated && (
          <span className="text-[10px] text-amber-700 bg-amber-50 border border-amber-200 px-2 py-0.5 rounded-full">
            ⚡ Auto dari anotasi
          </span>
        )}
      </div>

      <div
        className="relative bg-sky-50 rounded-xl overflow-visible border border-sky-100"
        onMouseLeave={() => setHoveredAnn(null)}
      >
        <img
          src={imageUrl}
          alt="Naskah"
          className="w-full block rounded-xl"
          draggable={false}
        />

        {annotations.map((a) => (
          <div
            key={`hit-${a.id}`}
            className="absolute cursor-pointer z-10"
            style={{
              left: `${Math.max(0, a.x - 0.005) * 100}%`,
              top: `${Math.max(0, a.y - 0.005) * 100}%`,
              width: `${(a.w + 0.01) * 100}%`,
              height: `${(a.h + 0.01) * 100}%`,
            }}
            onMouseEnter={() => setHoveredAnn(a)}
            onMouseLeave={() => setHoveredAnn(null)}
            onClick={() =>
              setSelectedAnn(selectedAnn?.id === a.id ? null : a)
            }
          />
        ))}

        {activeAnn && (
          <div
            className="absolute border-4 border-amber-500 bg-amber-400/30 transition-all duration-100 shadow-lg pointer-events-none z-20"
            style={{
              left: `${activeAnn.x * 100}%`,
              top: `${activeAnn.y * 100}%`,
              width: `${activeAnn.w * 100}%`,
              height: `${activeAnn.h * 100}%`,
            }}
          >
            <div className="absolute -top-9 left-0 bg-amber-500 text-white text-xs font-bold px-2 py-1 rounded shadow-lg whitespace-nowrap">
              {activeAnn.transliteration}
            </div>
          </div>
        )}

        {hoveredAnn && tooltipPosition && (
          <div
            className="absolute z-50 pointer-events-none bg-blue-900/95 text-white rounded-lg shadow-2xl
                       px-2.5 py-1.5 w-max max-w-[200px]
                       md:px-4 md:py-3 md:max-w-[380px]"
            style={{
              left: tooltipPosition.left,
              top: tooltipPosition.top,
              transform: tooltipPosition.transform,
            }}
          >
            <div className="grid grid-cols-2 gap-2 md:gap-4">
              <div>
                <p className="text-[8px] md:text-[10px] text-sky-300 uppercase tracking-wider mb-0.5 md:mb-1">
                  Alih Aksara
                </p>
                <p className="font-semibold text-[11px] md:text-sm leading-tight md:leading-snug">
                  {hoveredAnn.transliteration}
                </p>
              </div>

              <div className="border-l border-blue-800 pl-2 md:pl-4">
                <p className="text-[8px] md:text-[10px] text-sky-300 uppercase tracking-wider mb-0.5 md:mb-1">
                  Alih Bahasa
                </p>
                <p className="text-[10px] md:text-sm text-sky-100 leading-tight md:leading-snug">
                  {hoveredAnn.translation}
                </p>
              </div>
            </div>

            {hoveredAnn.notes && (
              <div className="border-t border-blue-800 mt-1.5 md:mt-3 pt-1.5 md:pt-3">
                <p className="text-[8px] md:text-[10px] text-sky-300 uppercase tracking-wider mb-0.5 md:mb-1">
                  Aparatus Kritis
                </p>
                <p className="text-[9px] md:text-xs text-sky-100 italic leading-tight md:leading-snug">
                  {hoveredAnn.notes}
                </p>
              </div>
            )}

            {tooltipPosition.arrowAtTop ? (
              <div className="absolute top-0 left-1/2 -translate-x-1/2 -translate-y-full">
                <div className="w-2.5 h-2.5 md:w-3 md:h-3 bg-blue-900/95 rotate-45 -mb-1 md:-mb-1.5"></div>
              </div>
            ) : (
              <div className="absolute bottom-0 left-1/2 -translate-x-1/2 translate-y-full">
                <div className="w-2.5 h-2.5 md:w-3 md:h-3 bg-blue-900/95 rotate-45 -mt-1 md:-mt-1.5"></div>
              </div>
            )}
          </div>
        )}
      </div>

      {annotations.length === 0 && !fullTransliteration ? (
        <div className="bg-white border border-sky-100 rounded-xl p-8 text-center text-slate-500 text-sm">
          Belum ada transliterasi untuk halaman ini.
        </div>
      ) : (
        <div className="grid md:grid-cols-2 gap-4">
          <div className="bg-white rounded-xl border border-sky-100 overflow-hidden shadow-sm">
            <div className="bg-blue-900 px-4 py-2.5 flex items-center justify-between">
              <div>
                <p className="text-[11px] font-bold text-white uppercase tracking-wider">
                  Alih Aksara
                </p>
                <p className="text-[9px] text-sky-300 uppercase tracking-wider">
                  Transliterasi Utuh
                </p>
              </div>
              <div className="flex items-center gap-1.5">
                {voiceSupported && (
                  <button
                    onClick={() => speak(translitParagraph, "translit-all")}
                    className={`inline-flex items-center justify-center w-7 h-7 rounded-full transition ${
                      speakingId === "translit-all"
                        ? "bg-amber-500 text-white shadow-md animate-pulse"
                        : "bg-white/20 text-white hover:bg-white/30"
                    }`}
                    title="Putar suara"
                  >
                    {speakingId === "translit-all" ? "⏸" : "🔊"}
                  </button>
                )}
                <span className="px-2 py-0.5 bg-white/20 text-white rounded text-[9px] font-medium uppercase tracking-wide">
                  Latin
                </span>
              </div>
            </div>
            <div className="p-4">
              <HighlightedParagraph
                text={translitParagraph}
                annotations={annotations}
                field="transliteration"
                hoveredId={hoveredAnn?.id || null}
                selectedId={selectedAnn?.id || null}
                onHover={setHoveredAnn}
                onSelect={(a) =>
                  setSelectedAnn(selectedAnn?.id === a.id ? null : a)
                }
              />
            </div>
          </div>

          <div className="bg-white rounded-xl border border-sky-100 overflow-hidden shadow-sm">
            <div className="bg-teal-700 px-4 py-2.5 flex items-center justify-between">
              <div>
                <p className="text-[11px] font-bold text-white uppercase tracking-wider">
                  Alih Bahasa
                </p>
                <p className="text-[9px] text-teal-200 uppercase tracking-wider">
                  Terjemahan Utuh
                </p>
              </div>
              <div className="flex items-center gap-1.5">
                {voiceSupported && (
                  <button
                    onClick={() =>
                      speak(translationParagraph, "translit-trans")
                    }
                    className={`inline-flex items-center justify-center w-7 h-7 rounded-full transition ${
                      speakingId === "translit-trans"
                        ? "bg-amber-500 text-white shadow-md animate-pulse"
                        : "bg-white/20 text-white hover:bg-white/30"
                    }`}
                    title="Putar suara"
                  >
                    {speakingId === "translit-trans" ? "⏸" : "🔊"}
                  </button>
                )}
                <span className="px-2 py-0.5 bg-white/20 text-white rounded text-[9px] font-medium uppercase tracking-wide">
                  Indonesia
                </span>
              </div>
            </div>
            <div className="p-4">
              <HighlightedParagraph
                text={translationParagraph}
                annotations={annotations}
                field="translation"
                hoveredId={hoveredAnn?.id || null}
                selectedId={selectedAnn?.id || null}
                onHover={setHoveredAnn}
                onSelect={(a) =>
                  setSelectedAnn(selectedAnn?.id === a.id ? null : a)
                }
              />
            </div>
          </div>
        </div>
      )}

      <p className="text-xs text-slate-500">
        💡 Arahkan kursor (atau tap) ke kata berwarna di paragraf{" "}
        <strong>atau</strong> ke kata di gambar naskah untuk melihat posisinya.
        Klik untuk detail lengkap.
      </p>

      {selectedAnn && (
        <div className="bg-white border border-sky-100 rounded-xl p-5 shadow-md">
          <div className="flex items-start justify-between mb-3">
            <div className="flex items-center gap-2">
              <div className="w-1 h-5 bg-teal-500 rounded"></div>
              <h3 className="font-bold text-blue-900">Detail Anotasi</h3>
            </div>
            <div className="flex items-center gap-3">
              <span className="text-xs text-slate-500">
                oleh {selectedAnn.contributorName}
              </span>
              <button
                onClick={() => setSelectedAnn(null)}
                className="text-xs text-slate-500 hover:text-teal-700 hover:underline"
              >
                Tutup
              </button>
            </div>
          </div>

          <div className="grid md:grid-cols-2 gap-4 text-sm">
            <div>
              <p className="text-xs text-slate-500 mb-0.5">Transliterasi</p>
              <p className="font-medium text-blue-900">
                {selectedAnn.transliteration}
              </p>
              {selectedAnn.pegonText && (
                <p className="text-xs text-slate-500 mt-1 font-mono">
                  {selectedAnn.pegonText}
                </p>
              )}
            </div>
            <div>
              <p className="text-xs text-slate-500 mb-0.5">Terjemahan</p>
              <p className="text-slate-700">{selectedAnn.translation}</p>
            </div>
          </div>

          {selectedAnn.notes && (
            <div className="mt-3 pt-3 border-t border-sky-100 text-sm">
              <p className="text-xs text-slate-500 mb-0.5">
                Aparatus Kritis
              </p>
              <p className="text-slate-600 italic">{selectedAnn.notes}</p>
            </div>
          )}
        </div>
      )}
    </div>
  );
}

function HighlightedParagraph({
  text,
  annotations,
  field,
  hoveredId,
  selectedId,
  onHover,
  onSelect,
}: {
  text: string;
  annotations: Annotation[];
  field: "transliteration" | "translation";
  hoveredId: string | null;
  selectedId: string | null;
  onHover: (a: Annotation | null) => void;
  onSelect: (a: Annotation) => void;
}) {
  if (!text.trim()) {
    return <p className="text-sm text-slate-400 italic">—</p>;
  }

  const wordMap = new Map<string, Annotation[]>();
  annotations.forEach((a) => {
    const value = a[field];
    if (!value) return;
    const words = value.split(/\s+/).filter((w) => w.length > 0);
    words.forEach((w) => {
      const key = w.toLowerCase().replace(/[^\w\u00C0-\u024F]/g, "");
      if (key) {
        if (!wordMap.has(key)) wordMap.set(key, []);
        wordMap.get(key)!.push(a);
      }
    });
  });

  const tokens = text.split(/(\s+)/);

  return (
    <p
      className="text-sm leading-relaxed text-slate-800"
      onMouseLeave={() => onHover(null)}
    >
      {tokens.map((token, i) => {
        if (!token.trim()) {
          return <span key={i}>{token}</span>;
        }

        const clean = token.toLowerCase().replace(/[^\w\u00C0-\u024F]/g, "");
        const anns = clean ? wordMap.get(clean) : null;

        if (!anns || anns.length === 0) {
          return <span key={i}>{token}</span>;
        }

        const activeMatch = anns.find(
          (a) => a.id === hoveredId || a.id === selectedId
        );
        const primaryAnn = activeMatch || anns[0];
        const isActive = !!activeMatch;

        const baseColor =
          "bg-amber-100 text-amber-900 border-b-2 border-amber-400";
        const activeColor =
          "bg-amber-300 text-amber-900 border-b-2 border-amber-500 shadow-sm";

        return (
          <mark
            key={i}
            className={`${
              isActive ? activeColor : baseColor
            } px-0.5 rounded cursor-pointer transition-colors duration-100`}
            onMouseEnter={() => onHover(primaryAnn)}
            onPointerEnter={() => onHover(primaryAnn)}
            onClick={() => onSelect(primaryAnn)}
          >
            {token}
          </mark>
        );
      })}
    </p>
  );
}